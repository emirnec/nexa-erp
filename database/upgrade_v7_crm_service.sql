BEGIN;

ALTER TABLE public."Customers"
    ADD COLUMN IF NOT EXISTS "CreditLimit" numeric(18,2) NOT NULL DEFAULT 0;

ALTER TABLE public."Sales"
    ADD COLUMN IF NOT EXISTS "DueDate" timestamp with time zone,
    ADD COLUMN IF NOT EXISTS "InstallmentCount" integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "IdempotencyKey" character varying(100);

ALTER TABLE public."Payments"
    ADD COLUMN IF NOT EXISTS "ServiceOrderId" integer,
    ADD COLUMN IF NOT EXISTS "IdempotencyKey" character varying(100);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_Sales_TenantId_IdempotencyKey"
    ON public."Sales" ("TenantId", "IdempotencyKey") WHERE "IdempotencyKey" IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Payments_TenantId_IdempotencyKey"
    ON public."Payments" ("TenantId", "IdempotencyKey") WHERE "IdempotencyKey" IS NOT NULL;

CREATE TABLE IF NOT EXISTS public."SaleInstallments" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId" integer NOT NULL,
    "SaleId" integer NOT NULL,
    "Sequence" integer NOT NULL,
    "DueDate" timestamp with time zone NOT NULL,
    "Amount" numeric(18,2) NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_SaleInstallments_TenantId_SaleId_Sequence"
    ON public."SaleInstallments" ("TenantId", "SaleId", "Sequence");
ALTER TABLE public."SaleInstallments" DROP CONSTRAINT IF EXISTS "FK_SaleInstallments_Tenant_Sale";
ALTER TABLE public."SaleInstallments"
    ADD CONSTRAINT "FK_SaleInstallments_Tenant_Sale"
    FOREIGN KEY ("TenantId", "SaleId") REFERENCES public."Sales"("TenantId", "Id") ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS public."Parts" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId" integer NOT NULL,
    "Code" character varying(60) NOT NULL,
    "Name" character varying(180) NOT NULL,
    "StockQuantity" integer NOT NULL DEFAULT 0,
    "PurchaseCost" numeric(18,2) NOT NULL DEFAULT 0,
    "SalePrice" numeric(18,2) NOT NULL DEFAULT 0,
    "IsActive" boolean NOT NULL DEFAULT true,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_Parts_TenantId_Code" ON public."Parts" ("TenantId", "Code");
ALTER TABLE public."Parts" DROP CONSTRAINT IF EXISTS "AK_Parts_TenantId_Id";
ALTER TABLE public."Parts" ADD CONSTRAINT "AK_Parts_TenantId_Id" UNIQUE ("TenantId", "Id");

CREATE TABLE IF NOT EXISTS public."ServiceOrders" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId" integer NOT NULL,
    "OrderNo" character varying(40) NOT NULL,
    "CustomerId" integer,
    "MotorcycleId" integer,
    "Status" character varying(30) NOT NULL DEFAULT 'Open',
    "Complaint" text,
    "Diagnosis" text,
    "Notes" text,
    "OpenedAt" timestamp with time zone NOT NULL DEFAULT now(),
    "DueDate" timestamp with time zone,
    "InvoicedAt" timestamp with time zone,
    "InvoiceNo" character varying(40),
    "TotalLabor" numeric(18,2) NOT NULL DEFAULT 0,
    "TotalParts" numeric(18,2) NOT NULL DEFAULT 0,
    "Total" numeric(18,2) NOT NULL DEFAULT 0,
    "PaidAmount" numeric(18,2) NOT NULL DEFAULT 0,
    "PaymentMethod" character varying(20) NOT NULL DEFAULT 'Cash'
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_ServiceOrders_TenantId_OrderNo" ON public."ServiceOrders" ("TenantId", "OrderNo");
CREATE INDEX IF NOT EXISTS "IX_ServiceOrders_TenantId_Status_OpenedAt" ON public."ServiceOrders" ("TenantId", "Status", "OpenedAt" DESC);
ALTER TABLE public."ServiceOrders" DROP CONSTRAINT IF EXISTS "AK_ServiceOrders_TenantId_Id";
ALTER TABLE public."ServiceOrders" ADD CONSTRAINT "AK_ServiceOrders_TenantId_Id" UNIQUE ("TenantId", "Id");
ALTER TABLE public."ServiceOrders" DROP CONSTRAINT IF EXISTS "FK_ServiceOrders_Tenant_Customer";
ALTER TABLE public."ServiceOrders" ADD CONSTRAINT "FK_ServiceOrders_Tenant_Customer"
    FOREIGN KEY ("TenantId", "CustomerId") REFERENCES public."Customers"("TenantId", "Id") ON DELETE RESTRICT;
ALTER TABLE public."ServiceOrders" DROP CONSTRAINT IF EXISTS "FK_ServiceOrders_Tenant_Motorcycle";
ALTER TABLE public."ServiceOrders" ADD CONSTRAINT "FK_ServiceOrders_Tenant_Motorcycle"
    FOREIGN KEY ("TenantId", "MotorcycleId") REFERENCES public."Motorcycles"("TenantId", "Id") ON DELETE RESTRICT;

CREATE TABLE IF NOT EXISTS public."ServiceOrderItems" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId" integer NOT NULL,
    "ServiceOrderId" integer NOT NULL,
    "Kind" character varying(20) NOT NULL DEFAULT 'Labor',
    "Description" character varying(200) NOT NULL,
    "Quantity" integer NOT NULL DEFAULT 1,
    "UnitPrice" numeric(18,2) NOT NULL DEFAULT 0,
    "UnitCost" numeric(18,2) NOT NULL DEFAULT 0,
    "PartId" integer
);
CREATE INDEX IF NOT EXISTS "IX_ServiceOrderItems_TenantId_ServiceOrderId"
    ON public."ServiceOrderItems" ("TenantId", "ServiceOrderId");
ALTER TABLE public."ServiceOrderItems" DROP CONSTRAINT IF EXISTS "FK_ServiceOrderItems_Tenant_Order";
ALTER TABLE public."ServiceOrderItems" ADD CONSTRAINT "FK_ServiceOrderItems_Tenant_Order"
    FOREIGN KEY ("TenantId", "ServiceOrderId") REFERENCES public."ServiceOrders"("TenantId", "Id") ON DELETE CASCADE;
ALTER TABLE public."ServiceOrderItems" DROP CONSTRAINT IF EXISTS "FK_ServiceOrderItems_Tenant_Part";
ALTER TABLE public."ServiceOrderItems" ADD CONSTRAINT "FK_ServiceOrderItems_Tenant_Part"
    FOREIGN KEY ("TenantId", "PartId") REFERENCES public."Parts"("TenantId", "Id") ON DELETE RESTRICT;

CREATE TABLE IF NOT EXISTS public."PartStockMovements" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TenantId" integer NOT NULL,
    "PartId" integer NOT NULL,
    "MovementType" character varying(30) NOT NULL,
    "Quantity" integer NOT NULL,
    "UnitCost" numeric(18,2) NOT NULL DEFAULT 0,
    "ServiceOrderId" integer,
    "Note" text,
    "CreatedAt" timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "IX_PartStockMovements_TenantId_PartId_CreatedAt"
    ON public."PartStockMovements" ("TenantId", "PartId", "CreatedAt" DESC);
ALTER TABLE public."PartStockMovements" DROP CONSTRAINT IF EXISTS "FK_PartStockMovements_Tenant_Part";
ALTER TABLE public."PartStockMovements" ADD CONSTRAINT "FK_PartStockMovements_Tenant_Part"
    FOREIGN KEY ("TenantId", "PartId") REFERENCES public."Parts"("TenantId", "Id") ON DELETE RESTRICT;
ALTER TABLE public."PartStockMovements" DROP CONSTRAINT IF EXISTS "FK_PartStockMovements_Tenant_ServiceOrder";
ALTER TABLE public."PartStockMovements" ADD CONSTRAINT "FK_PartStockMovements_Tenant_ServiceOrder"
    FOREIGN KEY ("TenantId", "ServiceOrderId") REFERENCES public."ServiceOrders"("TenantId", "Id") ON DELETE RESTRICT;
CREATE INDEX IF NOT EXISTS "IX_PartStockMovements_TenantId_ServiceOrderId"
    ON public."PartStockMovements" ("TenantId", "ServiceOrderId");

ALTER TABLE public."Payments" DROP CONSTRAINT IF EXISTS "FK_Payments_Tenant_ServiceOrder";
ALTER TABLE public."Payments" ADD CONSTRAINT "FK_Payments_Tenant_ServiceOrder"
    FOREIGN KEY ("TenantId", "ServiceOrderId") REFERENCES public."ServiceOrders"("TenantId", "Id") ON DELETE RESTRICT;

-- Oturum sürümü ve giriş kilidi alanları daha önce eklenmiş kurulumlarda da bulunsun.
ALTER TABLE public."AppUsers"
    ADD COLUMN IF NOT EXISTS "TokenVersion" integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "FailedLoginCount" integer NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "LockoutUntil" timestamp with time zone,
    ADD COLUMN IF NOT EXISTS "LastLoginAt" timestamp with time zone,
    ADD COLUMN IF NOT EXISTS "LastPasswordChangedAt" timestamp with time zone,
    ADD COLUMN IF NOT EXISTS "MustChangePassword" boolean NOT NULL DEFAULT false;

COMMIT;
