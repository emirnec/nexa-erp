-- Migration postgres ile çalıştırılsa bile yeni nesneleri uygulama kullanıcısına
-- (Sales tablosunun sahibi, üretimde 'nexa') devret. Aksi halde API permission denied alır.
DO $$
DECLARE
    app_owner name;
    object_name text;
BEGIN
    SELECT pg_get_userbyid(c.relowner) INTO app_owner
    FROM pg_class c WHERE c.oid = 'public."Sales"'::regclass;

    FOREACH object_name IN ARRAY ARRAY[
        'SaleInstallments', 'Parts', 'ServiceOrders', 'ServiceOrderItems', 'PartStockMovements'
    ] LOOP
        EXECUTE format('ALTER TABLE public.%I OWNER TO %I', object_name, app_owner);
    END LOOP;

    FOREACH object_name IN ARRAY ARRAY[
        'SaleInstallments_Id_seq', 'Parts_Id_seq', 'ServiceOrders_Id_seq',
        'ServiceOrderItems_Id_seq', 'PartStockMovements_Id_seq'
    ] LOOP
        IF to_regclass(format('public.%I', object_name)) IS NOT NULL THEN
            EXECUTE format('ALTER SEQUENCE public.%I OWNER TO %I', object_name, app_owner);
        END IF;
    END LOOP;
END $$;

COMMIT;
