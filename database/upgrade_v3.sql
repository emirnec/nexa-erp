CREATE TABLE IF NOT EXISTS "DealerStocks" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "DealerId" integer NOT NULL REFERENCES "Dealers"("Id") ON DELETE RESTRICT,
  "MotorcycleId" integer NOT NULL REFERENCES "Motorcycles"("Id") ON DELETE RESTRICT,
  "Quantity" integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_DealerStocks_DealerId_MotorcycleId" ON "DealerStocks" ("DealerId", "MotorcycleId");

CREATE TABLE IF NOT EXISTS "StockTransfers" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "MotorcycleId" integer NOT NULL REFERENCES "Motorcycles"("Id") ON DELETE RESTRICT,
  "FromDealerId" integer NOT NULL REFERENCES "Dealers"("Id") ON DELETE RESTRICT,
  "ToDealerId" integer NOT NULL REFERENCES "Dealers"("Id") ON DELETE RESTRICT,
  "Quantity" integer NOT NULL,
  "UnitCost" numeric(18,2) NOT NULL DEFAULT 0,
  "TransferType" text NOT NULL DEFAULT 'Consignment',
  "Status" text NOT NULL DEFAULT 'Draft',
  "Note" text NULL,
  "CreatedAt" timestamp with time zone NOT NULL DEFAULT now(),
  "ShippedAt" timestamp with time zone NULL,
  "ReceivedAt" timestamp with time zone NULL
);

