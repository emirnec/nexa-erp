UPDATE "Sales" s
SET "DealerId" = d."Id",
    "PaidAmount" = CASE WHEN s."IsCancelled" THEN 0 ELSE s."Quantity" * s."UnitPrice" END,
    "InvoiceNo" = COALESCE(s."InvoiceNo", 'SF-' || lpad(s."Id"::text, 6, '0'))
